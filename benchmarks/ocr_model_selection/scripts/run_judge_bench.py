"""Stages 2+3: the judge slot.

Production config is repeat=[2] + judge_mode=authoritative + judge_with_image=true,
so every page costs two OCR calls plus one judge call that re-emits the winning text.

Stage 2 -- judges on REAL production pairs (two repeats of the same OCR model).
          Measures cost, verbatim fidelity and end-to-end quality.
Stage 3 -- judges on DELIBERATELY UNEQUAL pairs. Stage 2 cannot separate judges
          because two repeats of one model rarely disagree. Here one candidate is
          objectively worse: it read fewer of the known chart values. That makes
          "which candidate is better" a counted fact rather than an opinion --
          the earlier study had to ask an LLM rubric for it.
          Both presentation orders x N repetitions, so position bias cancels and
          a rate above/below 0.5 is real discrimination.
"""
import concurrent.futures as cf, difflib, json, sys
from collections import defaultdict
from bench_common import (PAGES, RESULTS, TRUTH, call, image_b64, ocr_call,
                          recall, truth_tokens, data_hits, has_data)

OCR_MODEL = "google/gemini-3.1-flash-lite"
JUDGES = [
    "google/gemini-3-flash-preview",     # previous production judge
    "google/gemini-3.1-flash-lite",      # current production judge
    "google/gemini-2.5-flash-lite",
    "google/gemini-3.5-flash-lite",
    "google/gemini-3.6-flash",
]
REPS = int(sys.argv[1]) if len(sys.argv) > 1 else 3

INTRO = (
    "Below are the textual outputs generated by one or more OCR models for the image shown above. "
    "Your task is to act as an authoritative judge. Review all candidates carefully. "
    "Select the single candidate that provides the most accurate, complete, and well-formatted "
    "transcription of the image's content, including all text and descriptions of visual elements as requested in the original OCR prompt. "
    "Consider verbatim accuracy, preservation of formatting (Markdown, LaTeX), and the quality of visual descriptions.\n\n"
    "The candidates are:\n\n"
)
TAIL = ("\n\nBased on your assessment, please output ONLY the full text of the BEST candidate. "
        "Do NOT include the candidate number, model name, or any other commentary. "
        "Your response should be solely the chosen text itself.")

pages = sorted(PAGES.glob("*.png"), key=lambda p: int(p.stem.split("_")[1]))
raw = json.load(open(RESULTS / "ocr_raw.json", encoding="utf-8"))


def judge_blocks(page_name, cand_texts):
    enum = [f"Candidate {i+1} (from Model: model_{i+1}, Attempt: 1):\n---\n{t}\n---"
            for i, t in enumerate(cand_texts)]
    return [
        {"type": "text", "text": "This is the original image that was processed by the OCR models:"},
        {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image_b64(PAGES / page_name)}"}},
        {"type": "text", "text": INTRO + "\n\n".join(enum) + TAIL},
    ]


# ─────────────────────────── stage 2 ───────────────────────────
cand_file = RESULTS / "judge_candidates.json"
cands = json.load(open(cand_file, encoding="utf-8")) if cand_file.exists() else {}
todo = []
for p in pages:
    c = cands.setdefault(p.name, {})
    if "a" not in c:
        r = raw.get(f"{OCR_MODEL}||{p.name}")
        if r and r.get("ok"):
            c["a"] = r["text"]
    if "b" not in c:
        todo.append(p)
if todo:
    print(f"generating {len(todo)} second OCR repeats with {OCR_MODEL}")
    with cf.ThreadPoolExecutor(max_workers=5) as ex:
        for name, r in ex.map(lambda p: (p.name, ocr_call(OCR_MODEL, p)), todo):
            if r.get("ok"):
                cands[name]["b"] = r["text"]
    json.dump(cands, open(cand_file, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

s2file = RESULTS / "judge_real_pairs.json"
s2 = json.load(open(s2file, encoding="utf-8")) if s2file.exists() else {}


def run_real(job):
    j, name = job
    c = cands[name]
    r = call(j, judge_blocks(name, [c["a"], c["b"]]), title="pdf2anki-bench-judge")
    if not r.get("ok"):
        return f"{j}||{name}", {"ok": False, "error": r.get("error")}
    txt = r["text"]
    pg = name.replace(".png", "")
    sims = {k: difflib.SequenceMatcher(None, c[k], txt, autojunk=False).ratio() for k in "ab"}
    dh = data_hits(pg, txt) if has_data(pg) else None
    return f"{j}||{name}", {
        "ok": True, "text": txt, "cost": r.get("cost"), "lat": r.get("latency"),
        "verbatim": max(sims.values()), "pick": max(sims, key=sims.get),
        "recall": recall(truth_tokens(pg), txt),
        "hits": dh[0] if dh else None, "total": dh[1] if dh else None}


jobs2 = [(j, p.name) for j in JUDGES for p in pages
         if f"{j}||{p.name}" not in s2 or not s2[f"{j}||{p.name}"].get("ok")]
print(f"\nstage 2: {len(jobs2)} judge calls on real production pairs")
with cf.ThreadPoolExecutor(max_workers=5) as ex:
    for k, r in ex.map(run_real, jobs2):
        s2[k] = r
        print(f"  {'ok ' if r.get('ok') else 'ERR'} {k[:66]} verbatim={r.get('verbatim') and round(r['verbatim'],3)}", flush=True)
        json.dump(s2, open(s2file, "w", encoding="utf-8"), ensure_ascii=False)
json.dump(s2, open(s2file, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


# ─────────────────────────── stage 3 ───────────────────────────
# Build LENGTH-BALANCED pairs from pages with known values.
#
# Naively pairing "most hits vs. fewest hits" produced pairs in which the better
# candidate happened to also be the longer one -- every time. "picks the better
# candidate" and "picks the longer candidate" then become the same number and the
# test cannot tell fidelity from verbosity. So for each page we build BOTH
# orientations: one pair where the good candidate is shorter than the bad one, and
# one where it is longer. Averaged over both, a pure length preference scores 0.50.
models = sorted({k.split("||")[0] for k in raw})
pairs = []
for p in pages:
    pg = p.name.replace(".png", "")
    if not TRUTH[pg].get("vision_required"):
        continue
    scored = []
    for m in models:
        r = raw.get(f"{m}||{p.name}")
        if r and r.get("ok"):
            h, t, _ = data_hits(pg, r["text"])
            scored.append({"hits": h, "total": t, "model": m,
                           "text": r["text"], "len": len(r["text"])})
    if len(scored) < 2:
        continue
    best_h = max(s["hits"] for s in scored)
    goods = [s for s in scored if s["hits"] == best_h]
    bads = [s for s in scored if best_h - s["hits"] >= 2]
    if not bads:
        continue
    for orient in ("good_shorter", "good_longer"):
        cand = None
        for g in goods:
            for b in bads:
                ok = g["len"] < b["len"] if orient == "good_shorter" else g["len"] > b["len"]
                if not ok:
                    continue
                margin = abs(g["len"] - b["len"])
                if cand is None or margin > cand[0]:
                    cand = (margin, g, b)
        if cand is None:
            print(f"  [warn] {p.name}: no '{orient}' pair available -- orientation skipped")
            continue
        _, g, b = cand
        pairs.append({"page": p.name, "orient": orient,
                      "good_model": g["model"], "bad_model": b["model"],
                      "good_hits": g["hits"], "bad_hits": b["hits"], "total": g["total"],
                      "good_len": g["len"], "bad_len": b["len"],
                      "good": g["text"], "bad": b["text"]})

print(f"\nstage 3: {len(pairs)} length-balanced discriminative pair(s)")
for pr in pairs:
    print(f"  {pr['page']:12} {pr['orient']:13} "
          f"{pr['good_model'].split('/')[-1]} ({pr['good_hits']}/{pr['total']}, {pr['good_len']}c)"
          f"  vs  {pr['bad_model'].split('/')[-1]} ({pr['bad_hits']}/{pr['total']}, {pr['bad_len']}c)")

s3file = RESULTS / "judge_discriminative.json"
s3 = json.load(open(s3file, encoding="utf-8")) if s3file.exists() else {}


def run_disc(job):
    j, pr, order, rep = job
    seq = [pr["good"], pr["bad"]] if order == "good_first" else [pr["bad"], pr["good"]]
    r = call(j, judge_blocks(pr["page"], seq), title="pdf2anki-bench-judgedisc")
    key = f"{j}||{pr['page']}||{pr['orient']}||{order}||{rep}"
    if not r.get("ok"):
        return key, {"ok": False, "error": r.get("error")}
    out = r["text"]
    sg = difflib.SequenceMatcher(None, pr["good"], out, autojunk=False).ratio()
    sb = difflib.SequenceMatcher(None, pr["bad"], out, autojunk=False).ratio()
    return key, {"ok": True, "picked": "good" if sg >= sb else "bad",
                 "verbatim": max(sg, sb), "cost": r.get("cost"),
                 "longer": "good" if len(pr["good"]) > len(pr["bad"]) else "bad"}


jobs3 = [(j, pr, order, rep) for pr in pairs for order in ("good_first", "bad_first")
         for rep in range(REPS) for j in JUDGES
         if f"{j}||{pr['page']}||{pr['orient']}||{order}||{rep}" not in s3]
print(f"\n{len(jobs3)} discriminative judge calls ({REPS} reps x 2 orders)")
with cf.ThreadPoolExecutor(max_workers=5) as ex:
    for k, r in ex.map(run_disc, jobs3):
        s3[k] = r
        json.dump(s3, open(s3file, "w", encoding="utf-8"), ensure_ascii=False)
json.dump(s3, open(s3file, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
json.dump([{k: v for k, v in p.items() if k not in ("good", "bad")} for p in pairs],
          open(RESULTS / "judge_disc_pairs.json", "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)
print("done ->", s3file)
